# Task 2: Variables and Data Types
age = 20                 # Integer
percentage = 85.5        # Float
student_name = "Adarsh"  # String
is_student = True        # Boolean

print("Variable values and their data types:")
print("age =", age, "| type =", type(age))
print("percentage =", percentage, "| type =", type(percentage))
print("student_name =", student_name, "| type =", type(student_name))
print("is_student =", is_student, "| type =", type(is_student))
